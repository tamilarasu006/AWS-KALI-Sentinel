from typing import Dict, Any, Optional
import asyncio

from OpenDEMON.kali.intelligence.models import Plan, PlanStep, ExecutionResult
from OpenDEMON.kali.agents.manager import AgentManager
from OpenDEMON.kali.agents.models import AgentContext

class IntelligentExecutor:
    """
    Executes a Plan generated by the Planner.
    Iterates through the DAG, invoking the AgentManager for each step.
    Enforces security architecture by pushing execution through the Context.
    """
    def __init__(self, agent_manager: AgentManager):
        self.agent_manager = agent_manager
        
    async def execute_plan(self, plan: Plan, context_template: AgentContext) -> ExecutionResult:
        """
        Executes a plan resolving dependencies in topological order.
        For simplicity in this step, we loop and find available steps.
        """
        plan.status = "RUNNING"
        errors = []
        
        while True:
            # Find steps that are PENDING and whose dependencies are COMPLETED
            available_steps = []
            pending_count = 0
            
            for step in plan.steps:
                if step.status == "PENDING":
                    pending_count += 1
                    # Check if all deps are completed
                    deps_met = True
                    for dep_id in step.dependencies:
                        dep_step = plan.get_step(dep_id)
                        if not dep_step or dep_step.status != "COMPLETED":
                            deps_met = False
                            break
                    if deps_met:
                        available_steps.append(step)
                        
            if pending_count == 0:
                # All done
                plan.status = "COMPLETED"
                break
                
            if not available_steps:
                # Deadlock or failure propagated
                plan.status = "FAILED"
                errors.append("Execution stalled: dependencies could not be met or a previous step failed.")
                break
                
            # Execute available steps
            for step in available_steps:
                step.status = "RUNNING"
                
                # We inject previous outputs into the context state
                step_context = context_template.model_copy(deep=True)
                step_context.state["plan_goal"] = plan.goal
                step_context.state["current_step_id"] = step.id
                
                # Fetch agent
                agent = self.agent_manager.get(step.assigned_agent)
                if not agent:
                    # Try semantic routing if not explicitly named
                    agent = self.agent_manager.select_agent(step.description)
                    
                if not agent:
                    step.status = "FAILED"
                    step.error = f"Agent selection failed for '{step.assigned_agent}'"
                    errors.append(step.error)
                    continue
                    
                # Execute securely via RetryManager
                prompt = f"Goal: {plan.goal}\nTask: {step.description}\nVerification: {step.verification_criteria}"
                
                # Create a closure for the RetryManager to call
                async def execute_agent_thunk(p: str, ctx: AgentContext) -> Any:
                    return await self.agent_manager.execute_agent(agent.name, p, ctx)
                
                from OpenDEMON.kali.intelligence.correction.manager import RetryManager
                retry_manager = RetryManager()
                
                result = await retry_manager.execute_with_retry(
                    step=step,
                    initial_prompt=prompt,
                    context=step_context,
                    agent_executor=execute_agent_thunk
                )
                
                if result.success:
                    step.status = "COMPLETED"
                    step.result_output = result.output
                else:
                    step.status = "FAILED"
                    step.error = result.error
                    errors.append(f"Step {step.id} failed: {result.error}")
                    
        success = plan.status == "COMPLETED"
        return ExecutionResult(
            success=success,
            final_output="Plan executed." if success else "Plan execution failed.",
            plan=plan,
            errors=errors
        )
